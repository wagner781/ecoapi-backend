CREATE TABLE IF NOT EXISTS usuario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(80) UNIQUE NOT NULL, password VARCHAR(100) NOT NULL,
 nombre VARCHAR(120) NOT NULL, rol VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS rol_privilegio (
 rol VARCHAR(40) NOT NULL, privilegio VARCHAR(50) NOT NULL, PRIMARY KEY(rol, privilegio)
);
CREATE TABLE IF NOT EXISTS punto (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 razon_social VARCHAR(150) NOT NULL, direccion VARCHAR(200) NOT NULL,
 zona VARCHAR(80) NOT NULL, material_habitual VARCHAR(80) NOT NULL
);
CREATE TABLE IF NOT EXISTS ruta (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, fecha DATE NOT NULL,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id), cerrada BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS ruta_punto (
 ruta_id BIGINT REFERENCES ruta(id), punto_id BIGINT REFERENCES punto(id),
 secuencia INTEGER NOT NULL, motivo_omision VARCHAR(300), PRIMARY KEY(ruta_id,punto_id), UNIQUE(ruta_id,secuencia)
);
CREATE TABLE IF NOT EXISTS pesaje (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ruta_id BIGINT NOT NULL REFERENCES ruta(id), punto_id BIGINT NOT NULL REFERENCES punto(id),
 fecha_hora VARCHAR(50) NOT NULL, material VARCHAR(80) NOT NULL,
 peso_bruto NUMERIC(14,3) NOT NULL, tara NUMERIC(14,3) NOT NULL, peso_neto NUMERIC(14,3) NOT NULL,
 operario_id BIGINT NOT NULL REFERENCES usuario(id), observacion VARCHAR(500),
 anulado BOOLEAN NOT NULL DEFAULT FALSE, motivo_anulacion VARCHAR(300),
 clave_cliente VARCHAR(150), UNIQUE(operario_id,clave_cliente),
 CHECK(peso_bruto>0 AND tara>=0 AND peso_neto>0),
 FOREIGN KEY(ruta_id,punto_id) REFERENCES ruta_punto(ruta_id,punto_id)
);
