CREATE TABLE IF NOT EXISTS usuario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(80) UNIQUE NOT NULL, password VARCHAR(100) NOT NULL,
 nombre VARCHAR(120) NOT NULL, rol VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS rol_privilegio (
 rol VARCHAR(40) NOT NULL, privilegio VARCHAR(50) NOT NULL, PRIMARY KEY(rol, privilegio)
);
